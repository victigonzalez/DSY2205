-- 2. Creación de tablas
-- ------------------------------------------------------------
CREATE TABLE roles (
  id_rol        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        VARCHAR2(20)  NOT NULL CONSTRAINT uq_roles_nombre UNIQUE,
  descripcion   VARCHAR2(200)
);

CREATE TABLE usuarios (
  id_usuario     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         VARCHAR2(100) NOT NULL,
  username       VARCHAR2(30)  NOT NULL CONSTRAINT uq_usuarios_username UNIQUE,
  correo         VARCHAR2(120) NOT NULL CONSTRAINT uq_usuarios_correo UNIQUE,
  password       VARCHAR2(100) NOT NULL,
  activo         NUMBER(1)     DEFAULT 1 NOT NULL CONSTRAINT ck_usuarios_activo CHECK (activo IN (0,1)),
  fecha_registro TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  id_rol         NUMBER        NOT NULL CONSTRAINT fk_usuarios_rol REFERENCES roles(id_rol)
);

CREATE TABLE categorias (
  id_categoria  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        VARCHAR2(60)  NOT NULL CONSTRAINT uq_categorias_nombre UNIQUE,
  descripcion   VARCHAR2(250)
);

CREATE TABLE temas (
  id_tema         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo          VARCHAR2(150)  NOT NULL,
  contenido       VARCHAR2(4000) NOT NULL,
  fecha_creacion  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  estado          VARCHAR2(10)   DEFAULT 'ACTIVO' NOT NULL
                  CONSTRAINT ck_temas_estado CHECK (estado IN ('ACTIVO','BANEADO')),
  motivo_baneo    VARCHAR2(250),
  id_categoria    NUMBER NOT NULL CONSTRAINT fk_temas_categoria REFERENCES categorias(id_categoria),
  id_usuario      NUMBER NOT NULL CONSTRAINT fk_temas_usuario   REFERENCES usuarios(id_usuario) ON DELETE CASCADE
);

CREATE TABLE comentarios (
  id_comentario   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contenido       VARCHAR2(2000) NOT NULL,
  fecha_creacion  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  estado          VARCHAR2(10)   DEFAULT 'ACTIVO' NOT NULL
                  CONSTRAINT ck_comentarios_estado CHECK (estado IN ('ACTIVO','BANEADO')),
  motivo_baneo    VARCHAR2(250),
  id_tema         NUMBER NOT NULL CONSTRAINT fk_comentarios_tema    REFERENCES temas(id_tema)       ON DELETE CASCADE,
  id_usuario      NUMBER NOT NULL CONSTRAINT fk_comentarios_usuario REFERENCES usuarios(id_usuario) ON DELETE CASCADE
);

-- Índices para las búsquedas más frecuentes del foro
CREATE INDEX ix_temas_categoria     ON temas(id_categoria);
CREATE INDEX ix_temas_usuario       ON temas(id_usuario);
CREATE INDEX ix_comentarios_tema    ON comentarios(id_tema);

